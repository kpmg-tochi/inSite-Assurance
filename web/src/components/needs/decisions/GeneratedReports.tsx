import React, { useMemo, useState } from "react";
import { FileSpreadsheet, FileText, PenLine, RefreshCw, Sparkles } from "lucide-react";
import {
  CYCLE_DOCUMENT_KIND_META,
  NeedsReportKindEnum,
  stageConfigOf,
  type NeedsCycleDocumentDto,
  type NeedsCycleDto,
  type NeedsReportKind,
  type NeedsStage,
} from "@insite/shared";
import { getCycleDocumentLink } from "../../../api/needsPipeline";
import type { RegenerableReportKind } from "../../../api/needsDecisions";
import { useAuth } from "../../../lib/auth-context";
import { formatDateTimeShort } from "../../../lib/formatters";
import { useOpenNeedsFileMutation } from "../../../mutations/needs/useNeedsMutations";
import { useRegenerateNeedsReportMutation } from "../../../mutations/needs/useDecisionMutations";
import { cardCls, formatBytes, stageLabel } from "../needsUi";
import { cycleWritable } from "./decisionUi";
import { SignedCopyDialog } from "./SignedCopyDialog";

/**
 * Needs pipeline wave 3 (C5, D-N.5): the cycle's generated reports. Each report kind shows its current
 * files (Excel and PDF side by side, badge "Generated"), the earlier generations folded away, and the
 * signed copies people upload beside them (same kind, `generated: false`). The Validated Project List
 * and the Cost Estimate Report can be regenerated by the stage's actor or a cycle manager; the
 * Prioritised Project Portfolio is regenerated from the ranking (Prioritisation tab).
 */

const REPORT_STAGE: Record<NeedsReportKind, NeedsStage> = {
  VALIDATED_PROJECT_LIST: "VALIDATION",
  COST_ESTIMATE_REPORT: "COSTING",
  PRIORITISED_PROJECT_PORTFOLIO: "PRIORITISATION",
};

const isPdf = (d: NeedsCycleDocumentDto) => d.mimeType === "application/pdf" || d.fileName.toLowerCase().endsWith(".pdf");

export function GeneratedReports({ cycle, documents, canUploadSigned }: { cycle: NeedsCycleDto; documents: NeedsCycleDocumentDto[]; canUploadSigned: boolean }) {
  return (
    <section aria-labelledby="generated-reports" className="space-y-2">
      <h3 id="generated-reports" className="text-sm font-bold text-slate-900">
        Reports
      </h3>
      <div className="grid grid-cols-1 gap-3 lg:grid-cols-3">
        {NeedsReportKindEnum.options.map((kind) => (
          <ReportCard key={kind} cycle={cycle} kind={kind} documents={documents.filter((d) => d.kind === kind)} canUploadSigned={canUploadSigned} />
        ))}
      </div>
    </section>
  );
}

function ReportCard({
  cycle,
  kind,
  documents,
  canUploadSigned,
}: {
  cycle: NeedsCycleDto;
  kind: NeedsReportKind;
  documents: NeedsCycleDocumentDto[];
  canUploadSigned: boolean;
}) {
  const { user, hasPermission } = useAuth();
  const openFile = useOpenNeedsFileMutation();
  const regenerate = useRegenerateNeedsReportMutation(cycle.id);
  const [signing, setSigning] = useState(false);
  const stage = REPORT_STAGE[kind];
  const inPipeline = Boolean(stageConfigOf(cycle.config, stage));
  const supersededIds = useMemo(() => new Set(documents.map((d) => d.supersedesId).filter(Boolean)), [documents]);
  const generated = documents.filter((d) => d.generated);
  const current = generated.filter((d) => !supersededIds.has(d.id)).sort((a, b) => Number(isPdf(a)) - Number(isPdf(b)));
  const earlier = generated.filter((d) => supersededIds.has(d.id)).sort((a, b) => b.uploadedAt.localeCompare(a.uploadedAt));
  const signed = documents.filter((d) => !d.generated).sort((a, b) => Number(supersededIds.has(a.id)) - Number(supersededIds.has(b.id)) || b.uploadedAt.localeCompare(a.uploadedAt));
  const currentSigned = signed.find((d) => !supersededIds.has(d.id)) ?? null;

  const actor = stageConfigOf(cycle.config, stage)?.actorPermissionKey ?? null;
  const canRegenerate =
    kind !== "PRIORITISED_PROJECT_PORTFOLIO" && inPipeline && cycleWritable(cycle, user) && (hasPermission("needs:manage_cycle") || Boolean(actor && hasPermission(actor)));
  const latest = current[0] ?? null;
  const open = (d: NeedsCycleDocumentDto) => openFile.mutate(() => getCycleDocumentLink(cycle.id, d.id));

  return (
    <article className={`${cardCls} flex flex-col gap-2`} aria-label={CYCLE_DOCUMENT_KIND_META[kind].label}>
      <div className="flex flex-wrap items-start justify-between gap-2">
        <h4 className="text-xs font-bold text-slate-900">{CYCLE_DOCUMENT_KIND_META[kind].label}</h4>
        <span className="inline-flex items-center gap-1 rounded-full border border-brand-primary/25 bg-brand-primary/5 px-2 py-0.5 text-[10px] font-semibold text-brand-primary">
          <Sparkles className="h-3 w-3" aria-hidden="true" /> Generated
        </span>
      </div>

      {latest ? (
        <>
          <p className="text-[11px] text-slate-600">
            {formatDateTimeShort(latest.uploadedAt)} · {latest.uploadedByName} ·{" "}
            {latest.proposalIds.length === 0 ? "whole cycle" : `${latest.proposalIds.length} proposed project${latest.proposalIds.length === 1 ? "" : "s"}`}
          </p>
          <div className="flex flex-wrap gap-2">
            {current.map((d) => (
              <button
                key={d.id}
                type="button"
                disabled={openFile.isPending}
                onClick={() => open(d)}
                className="inline-flex items-center gap-1.5 rounded-xl border border-slate-300 px-3 py-1.5 text-xs font-semibold text-slate-800 hover:bg-slate-50 disabled:opacity-50"
                title={`${d.fileName} · ${formatBytes(d.byteSize)}`}
              >
                {isPdf(d) ? <FileText className="h-3.5 w-3.5 text-rose-700" aria-hidden="true" /> : <FileSpreadsheet className="h-3.5 w-3.5 text-emerald-700" aria-hidden="true" />}
                {isPdf(d) ? "PDF" : "Excel"}
                <span className="sr-only"> ({d.fileName})</span>
              </button>
            ))}
          </div>
        </>
      ) : (
        <p className="text-xs text-slate-500">
          {!inPipeline
            ? "This programme has no such stage."
            : kind === "PRIORITISED_PROJECT_PORTFOLIO"
              ? "Generated when the committee finalises the ranking (Prioritisation tab)."
              : `Not generated yet. It is produced when the ${stageLabel(cycle, stage).toLowerCase()} decision is recorded.`}
        </p>
      )}

      {earlier.length > 0 && (
        <details className="text-[11px] text-slate-600">
          <summary className="cursor-pointer font-semibold text-slate-700">Earlier versions ({earlier.length})</summary>
          <ul className="mt-1 space-y-0.5">
            {earlier.map((d) => (
              <li key={d.id} className="flex flex-wrap items-baseline justify-between gap-2">
                <span>
                  {isPdf(d) ? "PDF" : "Excel"} · {formatDateTimeShort(d.uploadedAt)}
                </span>
                <button type="button" className="font-semibold text-brand-primary hover:underline disabled:opacity-50" disabled={openFile.isPending} onClick={() => open(d)}>
                  Open
                </button>
              </li>
            ))}
          </ul>
        </details>
      )}

      <div className="mt-auto space-y-1 border-t border-slate-100 pt-2">
        <p className="text-[11px] font-semibold text-slate-700">Signed copy</p>
        {signed.length === 0 ? (
          <p className="text-[11px] text-slate-500">None uploaded.</p>
        ) : (
          <ul className="space-y-0.5 text-[11px]">
            {signed.map((d) => (
              <li key={d.id} className={`flex flex-wrap items-baseline justify-between gap-2 ${supersededIds.has(d.id) ? "text-slate-400" : "text-slate-700"}`}>
                <span>
                  {d.title}
                  {supersededIds.has(d.id) ? " (superseded)" : ""} · {formatDateTimeShort(d.uploadedAt)}
                </span>
                <button type="button" className="font-semibold text-brand-primary hover:underline disabled:opacity-50" disabled={openFile.isPending} onClick={() => open(d)}>
                  Open
                </button>
              </li>
            ))}
          </ul>
        )}
        <div className="flex flex-wrap gap-2 pt-1">
          {canUploadSigned && latest && (
            <button type="button" className="inline-flex items-center gap-1 text-xs font-semibold text-brand-primary hover:underline" onClick={() => setSigning(true)}>
              <PenLine className="h-3.5 w-3.5" aria-hidden="true" /> {currentSigned ? "Replace the signed copy" : "Upload the signed copy"}
            </button>
          )}
          {canRegenerate && (
            <button
              type="button"
              className="inline-flex items-center gap-1 text-xs font-semibold text-slate-700 hover:underline disabled:opacity-50"
              disabled={regenerate.isPending}
              onClick={() => regenerate.mutate(kind as RegenerableReportKind)}
            >
              <RefreshCw className={`h-3.5 w-3.5 ${regenerate.isPending ? "animate-spin motion-reduce:animate-none" : ""}`} aria-hidden="true" />
              {regenerate.isPending ? "Generating…" : latest ? "Regenerate" : "Generate now"}
            </button>
          )}
        </div>
      </div>

      {signing && latest && (
        <SignedCopyDialog cycleId={cycle.id} kind={kind} proposalIds={latest.proposalIds} supersedesId={currentSigned?.id ?? null} onClose={() => setSigning(false)} />
      )}
    </article>
  );
}
