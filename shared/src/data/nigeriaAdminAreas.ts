/**
 * Nigeria's administrative areas (client demo updates C1): 6 geopolitical zones,
 * 36 States + FCT, 774 LGAs. Bundled (the field app needs it offline).
 *
 * Codes are stable contract values stored in the database:
 * - zone: two letters (NC, NE, NW, SE, SS, SW);
 * - state: the ISO 3166-2:NG suffix (FC for the FCT, KN for Kano, LA for Lagos, ...);
 * - LGA: `<stateCode>-<SLUG>` where SLUG is the upper-case name with every run of
 *   non-alphanumerics replaced by one hyphen (e.g. `KN-KANO-MUNICIPAL`, `FC-ABUJA-MUNICIPAL`).
 */

