/** Validates a stored LGA code (format only; membership checked with `lgaByCode`). */
export const NigeriaLgaCodeSchema = z
  .string()
  .trim()
  .toUpperCase()
  .regex(/^[A-Z]{2}-[A-Z0-9-]+$/, 'Unknown LGA');

const STATE_BY_CODE = new Map(NIGERIA_STATES.map((s) => [s.code, s]));

export function stateByCode(code: string | null | undefined): NigeriaState | null {
  if (!code) return null;
  return STATE_BY_CODE.get(code.trim().toUpperCase()) ?? null;
}

export function zoneOfState(code: string | null | undefined): NigeriaZoneCode | null {
  return stateByCode(code)?.zone ?? null;
}

export function zoneName(code: string | null | undefined): string | null {
  return NIGERIA_ZONES.find((z) => z.code === code)?.name ?? null;
}

export function statesOfZone(zone: NigeriaZoneCode): NigeriaState[] {
  return NIGERIA_STATES.filter((s) => s.zone === zone);
}

export function lgaByCode(code: string | null | undefined): NigeriaLga | null {
  if (!code) return null;
  const c = code.trim().toUpperCase();
  return NIGERIA_LGAS.find((l) => l.code === c) ?? null;
}

export function lgasOfState(stateCode: string | null | undefined): NigeriaLga[] {
  if (!stateCode) return [];
  const c = stateCode.trim().toUpperCase();
  return NIGERIA_LGAS.filter((l) => l.stateCode === c);
}

function normaliseName(value: string): string {
  return value
    .toLowerCase()
    .replace(/\bstate\b/g, '')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
}

/** Lenient lookup by name or code ("Kano", "kano state", "KN", "FCT", "Abuja"). */
export function findStateByName(value: string | null | undefined): NigeriaState | null {
  if (!value) return null;
  const byCode = stateByCode(value);
  if (byCode) return byCode;
  const n = normaliseName(value);
  if (!n) return null;
  if (n === 'fct' || n === 'abuja' || n === 'federal capital territory' || n === 'fct abuja') {
    return STATE_BY_CODE.get('FC') ?? null;
  }
  return NIGERIA_STATES.find((s) => normaliseName(s.name) === n) ?? null;
}

/** Lenient lookup of an LGA by name within a state. */
export function findLgaByName(stateCode: string | null | undefined, value: string | null | undefined): NigeriaLga | null {
  if (!value) return null;
  const byCode = lgaByCode(value);
  if (byCode) return !stateCode || byCode.stateCode === stateCode.trim().toUpperCase() ? byCode : null;
  const n = normaliseName(value);
  return lgasOfState(stateCode).find((l) => normaliseName(l.name) === n) ?? null;
}
